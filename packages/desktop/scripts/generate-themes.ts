/**
 * Writes the ported themes (decision 064): one module per palette in `palettes/` under
 * `src/appearance/themes/`, and their index. Run by hand after re-vendoring, and commit the result:
 * `bun packages/desktop/scripts/generate-themes.ts`. A palette whose solved theme fails the audit
 * stops the run and writes nothing.
 *
 * Every colour is read from the palette and then moved only as far as the audit needs: an ink
 * toward white (dark) or black (light) until it is readable, a tint behind text back toward the
 * canvas until the ink on it is readable, a datasource tint around the hue circle until it is
 * apart from the others.
 */
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";
import type { ColorTokens, DatasourceTint, Theme } from "@table-craft/desktop/appearance/themes.js";
import { requiredContrast } from "@table-craft/desktop/appearance/contrast.js";
import {
  BLACK,
  WHITE,
  contrast,
  flatten,
  fromOklch,
  furthest,
  mix,
  nearest,
  oklch,
  parseColor,
  perceptualDistance,
  quantise,
  toHex,
  type Rgb,
} from "./colour.js";
import {
  DATASOURCE_TINTS,
  TINT_MIN_CONTRAST,
  TINT_MIN_DISTANCE,
  contrastViolations,
  tintViolations,
} from "./theme-audit.js";

const SCRIPTS = fileURLToPath(new URL(".", import.meta.url));
export const PALETTE_DIRECTORY = join(SCRIPTS, "palettes");
export const THEME_DIRECTORY = join(SCRIPTS, "..", "src", "appearance", "themes");
const NOTICE_FILE = "NOTICE";
const OVERRIDES_FILE = "overrides.json";
const INDEX_FILE = "index.ts";
export const GENERATED_HEADER = "// Generated by scripts/generate-themes.ts. Do not edit.";

/** Solved colours land this far past their floor, so a reader's rounding never lands under it. */
const MARGIN = 1.02;
const TEXT = requiredContrast("aa", "text") * MARGIN;
const INK = requiredContrast("aa", "ink") * MARGIN;
const TINT = TINT_MIN_CONTRAST * MARGIN;
const TINT_DISTANCE = TINT_MIN_DISTANCE * MARGIN;

/** How much of its colour a tint behind text starts with, before the ink check pulls it back. */
const EDIT_TINT_WEIGHT = 0.22;
const GRID_SELECTION_WEIGHT = 0.35;
const BRACKET_MATCH_WEIGHT = 0.25;
const SEARCH_MATCH_WEIGHT = 0.35;
const FLASH_WEIGHT = 0.18;
const GRID_STRIPE_WEIGHT = 0.03;
const DEGREE = Math.PI / 180;
const TINT_HUE_STEP = 10 * DEGREE;
const TINT_HUE_STEPS = 18;
const TINT_LIGHTNESS_STEP = 0.04;
const TINT_LIGHTNESS_STEPS = 6;
/** Below this an OKLCH colour is a grey, and rotating its hue moves nothing. */
const TINT_MIN_CHROMA = 0.08;
/** Each tint's hue in OKLCH, and where it goes when its palette has nothing near it. */
const TINT_HUE: Readonly<Record<DatasourceTint, number>> = {
  red: 25 * DEGREE,
  orange: 55 * DEGREE,
  yellow: 100 * DEGREE,
  green: 145 * DEGREE,
  blue: 250 * DEGREE,
  violet: 305 * DEGREE,
};
/** The palette colours a datasource tint is picked from: the one nearest the tint's hue. */
const TINT_SOURCES = [
  "status.error",
  "status.warning",
  "status.success",
  "status.info",
  "primary.base",
  "pr.open",
  "pr.merged",
  "pr.closed",
  "syntax.base.keyword",
  "syntax.base.string",
  "syntax.base.number",
  "syntax.base.function",
  "syntax.base.type",
  "syntax.base.operator",
] as const;
/** How far from a tint's hue a palette colour may be and still be called that tint. */
const TINT_MAX_HUE_DRIFT = 35 * DEGREE;

const FALLBACK_LIGHTNESS = { dark: 0.72, light: 0.55 } as const;
const FALLBACK_CHROMA = 0.13;

export class PaletteError extends Error {
  override readonly name = "PaletteError";
}

interface Palette {
  readonly metadata: { readonly id: string; readonly name: string; readonly variant: "dark" | "light" };
  readonly colors: Readonly<Record<string, unknown>>;
}

export interface Attribution {
  readonly source: string;
  readonly licence: string;
}

type Overrides = Readonly<Record<string, Partial<Record<string, unknown>>>>;

function lookup(palette: Palette, path: string): string | undefined {
  let value: unknown = palette.colors;
  for (const key of path.split(".")) {
    value = typeof value === "object" && value !== null ? (value as Record<string, unknown>)[key] : undefined;
  }
  return typeof value === "string" ? value : undefined;
}

function required(palette: Palette, path: string): string {
  const value = lookup(palette, path);
  if (value === undefined)
    throw new PaletteError(`${palette.metadata.id} has no colors.${path}; add it to the palette.`);
  return value;
}

/** The `Palette  Source  Licence` table in `NOTICE`: the one place attribution is written. */
export function readAttribution(notice: string): ReadonlyMap<string, Attribution> {
  const rows = new Map<string, Attribution>();
  const table = notice.slice(notice.indexOf("    Palette"));
  for (const line of table.split("\n").slice(1)) {
    const cells = line.trim().split(/ {2,}/);
    if (cells.length !== 3) break;
    const [family = "", source = "", licence = ""] = cells;
    rows.set(family, { source, licence });
  }
  return rows;
}

/** The longest family a palette id starts with: `mono-plus-dark` is Mono+, not Mono. */
export function familyOf(id: string, families: Iterable<string>): string {
  const matches = [...families].filter((family) => id === family || id.startsWith(`${family}-`));
  const [best] = matches.sort((a, b) => b.length - a.length);
  if (best === undefined) throw new PaletteError(`${id} has no row in palettes/NOTICE; add its source and licence.`);
  return best;
}

function displayName(palette: Palette): string {
  const { name, variant } = palette.metadata;
  const suffix = variant === "dark" ? "Dark" : "Light";
  return name.toLowerCase().endsWith(variant) ? name : `${name} ${suffix}`;
}

function hueGap(a: number, b: number): number {
  const gap = Math.abs(a - b) % (2 * Math.PI);
  return Math.min(gap, 2 * Math.PI - gap);
}

function solveTints(candidates: readonly Rgb[], panel: Rgb, dark: boolean) {
  const extreme = dark ? WHITE : BLACK;
  const taken: Rgb[] = [];
  const solved = {} as Record<DatasourceTint, string>;
  const seeds = new Map<DatasourceTint, Rgb>();
  const used = new Set<Rgb>();
  const pairs = candidates
    .filter((candidate) => oklch(candidate).c >= TINT_MIN_CHROMA)
    .flatMap((candidate) =>
      DATASOURCE_TINTS.map((tint) => ({ tint, candidate, gap: hueGap(oklch(candidate).h, TINT_HUE[tint]) })),
    )
    .filter((pair) => pair.gap <= TINT_MAX_HUE_DRIFT)
    .sort((a, b) => a.gap - b.gap);
  for (const { tint, candidate } of pairs) {
    if (seeds.has(tint) || used.has(candidate)) continue;
    seeds.set(tint, candidate);
    used.add(candidate);
  }
  for (const tint of DATASOURCE_TINTS) {
    const fallback = fromOklch({
      l: FALLBACK_LIGHTNESS[dark ? "dark" : "light"],
      c: FALLBACK_CHROMA,
      h: TINT_HUE[tint],
    });
    const seed = seeds.get(tint) ?? fallback;
    const polar = oklch(seed);
    const chroma = Math.max(polar.c, TINT_MIN_CHROMA);
    const steps = (count: number, size: number) =>
      Array.from({ length: count }, (_, index) => (index + 1) * size).flatMap((offset) => [offset, -offset]);
    const rotations = steps(TINT_HUE_STEPS, TINT_HUE_STEP)
      .map((turn) => polar.h + turn)
      .filter((hue) => hueGap(hue, TINT_HUE[tint]) <= TINT_MAX_HUE_DRIFT)
      .map((hue) => fromOklch({ l: polar.l, c: chroma, h: hue }));
    const shades = (from: Rgb) =>
      steps(TINT_LIGHTNESS_STEPS, TINT_LIGHTNESS_STEP).map((shift) => {
        const base = oklch(from);
        return fromOklch({ ...base, l: base.l + shift });
      });
    const chosen = [seed, ...rotations, ...shades(seed), fallback, ...shades(fallback)]
      .map((candidate) => nearest(candidate, extreme, (colour) => contrast(colour, panel) >= TINT))
      .find((candidate) => taken.every((other) => perceptualDistance(candidate, other) >= TINT_DISTANCE));
    if (chosen === undefined) throw new PaletteError(`no datasource ${tint} sits apart from the others.`);
    taken.push(chosen);
    solved[tint] = toHex(chosen);
  }
  return solved;
}

/** One palette as a theme, before the audit. */
export function themeOf(palette: Palette, attribution: Attribution, overrides: Overrides = {}): Theme {
  const dark = palette.metadata.variant === "dark";
  const extreme = dark ? WHITE : BLACK;
  const canvas = quantise(flatten(parseColor(required(palette, "surface.background")), dark ? BLACK : WHITE));
  const over = (base: Rgb) => (path: string) => quantise(flatten(parseColor(required(palette, path)), base));
  const onCanvas = over(canvas);
  const panel = onCanvas("surface.muted");
  const raised = onCanvas("surface.elevated");
  const surfaces = [canvas, panel, raised];
  const readable = (colour: Rgb, on: readonly Rgb[], target = TEXT): Rgb =>
    nearest(colour, extreme, (candidate) => on.every((surface) => contrast(candidate, surface) >= target));

  const ink = readable(onCanvas("surface.foreground"), surfaces, INK);
  const accent = readable(onCanvas("primary.base"), surfaces);
  const accentInkSeed = onCanvas("primary.foreground");
  const accentInk =
    [accentInkSeed, canvas, BLACK, WHITE].find((candidate) => contrast(candidate, accent) >= TEXT) ?? accentInkSeed;
  const danger = readable(onCanvas("status.error"), surfaces);
  const success = readable(onCanvas("status.success"), surfaces);
  const warning = readable(onCanvas("status.warning"), surfaces);
  const behindInk = (tint: Rgb, weight: number, base = canvas): Rgb =>
    nearest(mix(base, tint, weight), base, (candidate) => contrast(ink, candidate) >= INK);
  const syntaxOf = (...paths: string[]): Rgb => {
    const path = paths.find((candidate) => lookup(palette, candidate) !== undefined) ?? paths[0] ?? "";
    return readable(onCanvas(path), [canvas]);
  };

  const colors: ColorTokens = {
    canvas: toHex(canvas),
    panel: toHex(panel),
    raised: toHex(raised),
    border: toHex(onCanvas("interactive.border")),
    ink: toHex(ink),
    inkMuted: toHex(readable(onCanvas("surface.mutedForeground"), surfaces)),
    accent: toHex(accent),
    accentInk: toHex(accentInk),
    danger: toHex(danger),
    success: toHex(success),
    gridStripe: toHex(quantise(mix(canvas, ink, GRID_STRIPE_WEIGHT))),
    gridSelection: toHex(behindInk(accent, GRID_SELECTION_WEIGHT)),
    gridNull: toHex(furthest(ink, canvas, (candidate) => contrast(candidate, canvas) >= TEXT)),
    editModified: toHex(behindInk(accent, EDIT_TINT_WEIGHT)),
    editInserted: toHex(behindInk(success, EDIT_TINT_WEIGHT)),
    editDeleted: toHex(behindInk(danger, EDIT_TINT_WEIGHT)),
    selection: toHex(behindInk(over(panel)("interactive.selection"), 1, panel)),
    searchMatch: toHex(behindInk(warning, SEARCH_MATCH_WEIGHT)),
    keyIcon: toHex(warning),
    warning: toHex(warning),
    statementFlash: toHex(behindInk(success, FLASH_WEIGHT)),
    planBar: toHex(accent),
    analysedBanner: toHex(behindInk(warning, FLASH_WEIGHT)),
    datasource: solveTints(
      TINT_SOURCES.filter((path) => lookup(palette, path) !== undefined).map(onCanvas),
      panel,
      dark,
    ),
    syntax: {
      keyword: toHex(syntaxOf("syntax.base.keyword")),
      string: toHex(syntaxOf("syntax.base.string")),
      number: toHex(syntaxOf("syntax.base.number")),
      comment: toHex(syntaxOf("syntax.base.comment")),
      identifier: toHex(syntaxOf("syntax.base.type")),
      operator: toHex(syntaxOf("syntax.base.operator")),
      variable: toHex(syntaxOf("syntax.tokens.parameter", "syntax.base.function")),
      bracketMatch: toHex(behindInk(accent, BRACKET_MATCH_WEIGHT)),
    },
  };
  const override = overrides[palette.metadata.id] ?? {};
  const { syntax, datasource, ...flat } = override as Partial<ColorTokens>;
  return {
    id: palette.metadata.id as Theme["id"],
    name: displayName(palette),
    colorScheme: palette.metadata.variant,
    contrast: "aa",
    source: attribution.source,
    licence: attribution.licence,
    colors: {
      ...colors,
      ...flat,
      syntax: { ...colors.syntax, ...syntax },
      datasource: { ...colors.datasource, ...datasource },
    },
  };
}

function constantOf(id: string): string {
  return id.toUpperCase().replaceAll("-", "_");
}

async function formatted(source: string, file: string): Promise<string> {
  return format(source, { ...(await resolveConfig(file)), filepath: file });
}

/** Every palette, solved, audited and rendered: file name to contents. Throws listing every fault. */
export async function renderThemeModules(): Promise<ReadonlyMap<string, string>> {
  const attribution = readAttribution(await readFile(join(PALETTE_DIRECTORY, NOTICE_FILE), "utf8"));
  const overrides = JSON.parse(await readFile(join(PALETTE_DIRECTORY, OVERRIDES_FILE), "utf8")) as Overrides;
  const files = (await readdir(PALETTE_DIRECTORY)).filter((file) => file.endsWith(".json") && file !== OVERRIDES_FILE);
  const themes = await Promise.all(
    files.map(async (file) => {
      const palette = JSON.parse(await readFile(join(PALETTE_DIRECTORY, file), "utf8")) as Palette;
      const family = familyOf(palette.metadata.id, attribution.keys());
      return themeOf(palette, attribution.get(family) ?? { source: family, licence: "" }, overrides);
    }),
  );
  themes.sort((a, b) => a.name.localeCompare(b.name) || a.id.localeCompare(b.id));
  const faults = themes.flatMap((theme) => [...contrastViolations(theme), ...tintViolations(theme, { onPanel: true })]);
  if (faults.length > 0) {
    throw new PaletteError(
      `${String(faults.length)} audit failures; fix the palette or add an override in palettes/overrides.json:\n${faults.join("\n")}`,
    );
  }

  const modules = new Map<string, string>();
  for (const theme of themes) {
    const file = join(THEME_DIRECTORY, `${theme.id}.ts`);
    const source = `${GENERATED_HEADER}\nimport type { Theme } from "@table-craft/desktop/appearance/themes.js";\n\nexport const ${constantOf(theme.id)}: Theme = ${JSON.stringify(theme)};\n`;
    modules.set(`${theme.id}.ts`, await formatted(source, file));
  }
  const index = [
    GENERATED_HEADER,
    `import type { Theme } from "@table-craft/desktop/appearance/themes.js";`,
    ...themes.map((theme) => `import { ${constantOf(theme.id)} } from "./${theme.id}.js";`),
    "",
    `export const PORTED_THEME_IDS = ${JSON.stringify(themes.map((theme) => theme.id))} as const;`,
    "",
    "export type PortedThemeId = (typeof PORTED_THEME_IDS)[number];",
    "",
    `export const PORTED_THEMES: Readonly<Record<PortedThemeId, Theme>> = {${themes.map((theme) => `"${theme.id}": ${constantOf(theme.id)}`).join(", ")}};`,
    "",
  ].join("\n");
  modules.set(INDEX_FILE, await formatted(index, join(THEME_DIRECTORY, INDEX_FILE)));
  return modules;
}

async function writeThemeModules(): Promise<void> {
  const modules = await renderThemeModules();
  await mkdir(THEME_DIRECTORY, { recursive: true });
  const stale = (await readdir(THEME_DIRECTORY)).filter((file) => !modules.has(file));
  await Promise.all(stale.map((file) => rm(join(THEME_DIRECTORY, file))));
  for (const [file, contents] of modules) await writeFile(join(THEME_DIRECTORY, file), contents);
  console.log(`Wrote ${String(modules.size - 1)} themes to ${THEME_DIRECTORY}.`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await writeThemeModules();
