/**
 * Writes `src/docs.generated.ts` and `src/subcommands.generated.ts` from a Redis 7.4 server's
 * `COMMAND DOCS` and `COMMAND INFO` (plan 058 decisions 8 and 24): the docs a 6.2 server cannot
 * give, and the flags of container subcommands it does not list. Run against the `redis` test
 * service: `bun plugins/redis/scripts/command-docs.ts [host:port]`.
 */
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { createClient, RESP_TYPES } from "redis";

const DEFAULT_ADDRESS = "127.0.0.1:56379";
const CREDENTIALS = { username: "table_craft", password: "table_craft" };
const DOCS_FILE = fileURLToPath(new URL("../src/docs.generated.ts", import.meta.url));
const FLAGS_FILE = fileURLToPath(new URL("../src/subcommands.generated.ts", import.meta.url));
const INFO_FLAGS = 2;
const INFO_SUBCOMMANDS = 9;

type Reply = string | number | null | Reply[] | Map<string, Reply>;

interface Argument {
  readonly name: string;
  readonly type: string;
  readonly token?: string;
  readonly optional?: true;
  readonly multiple?: true;
  readonly arguments?: readonly Argument[];
}

interface Doc {
  readonly summary: string;
  readonly since: string;
  readonly group: string;
  readonly arguments?: readonly Argument[];
}

function field(map: Reply, name: string): Reply | undefined {
  return map instanceof Map ? map.get(name) : undefined;
}

function text(value: Reply | undefined): string {
  return typeof value === "string" ? value : "";
}

function argumentOf(raw: Reply): Argument {
  const flags = field(raw, "flags");
  const list = Array.isArray(flags) ? flags : [];
  const children = field(raw, "arguments");
  const token = text(field(raw, "token"));
  return {
    name: text(field(raw, "name")),
    type: text(field(raw, "type")),
    ...(token === "" ? {} : { token }),
    ...(list.includes("optional") ? { optional: true } : {}),
    ...(list.includes("multiple") ? { multiple: true } : {}),
    ...(Array.isArray(children) ? { arguments: children.map(argumentOf) } : {}),
  };
}

function docOf(raw: Reply): Doc {
  const args = field(raw, "arguments");
  return {
    summary: text(field(raw, "summary")),
    since: text(field(raw, "since")),
    group: text(field(raw, "group")),
    ...(Array.isArray(args) ? { arguments: args.map(argumentOf) } : {}),
  };
}

function commandName(name: string): string {
  return name.replace("|", " ").toUpperCase();
}

async function main(): Promise<void> {
  const [host = "", port = ""] = (process.argv[2] ?? DEFAULT_ADDRESS).split(":");
  const client = createClient({ socket: { host, port: Number(port) }, ...CREDENTIALS, RESP: 3 });
  await client.connect();
  const typed = client.withTypeMapping({ [RESP_TYPES.MAP]: Map });
  const docs = new Map<string, Doc>();
  const all = await typed.sendCommand<Map<string, Reply>>(["COMMAND", "DOCS"]);
  for (const [name, raw] of all) {
    if (name.includes(".")) continue; // a module's command, absent from a plain server
    docs.set(commandName(name), docOf(raw));
    const subcommands = field(raw, "subcommands");
    if (subcommands instanceof Map) {
      for (const [sub, subRaw] of subcommands) docs.set(commandName(sub), docOf(subRaw));
    }
  }
  const flags = new Map<string, readonly string[]>();
  const info = await typed.sendCommand<Reply[][]>(["COMMAND"]);
  for (const entry of info) {
    const name = text(entry[0]);
    if (name.includes(".")) continue;
    flags.set(commandName(name), (entry[INFO_FLAGS] as string[] | undefined) ?? []);
    const subcommands = entry[INFO_SUBCOMMANDS];
    for (const sub of Array.isArray(subcommands) ? subcommands : []) {
      if (Array.isArray(sub)) flags.set(commandName(text(sub[0])), (sub[INFO_FLAGS] as string[] | undefined) ?? []);
    }
  }
  const version = text((await client.sendCommand<string>(["INFO", "server"])).match(/redis_version:(\S+)/)?.[1]);
  await client.close();
  const sorted = <T>(map: Map<string, T>): Record<string, T> =>
    Object.fromEntries([...map].sort(([a], [b]) => a.localeCompare(b)));
  const header = `// Generated by plugins/redis/scripts/command-docs.ts from Redis ${version}; do not edit.\n`;
  await writeFile(
    DOCS_FILE,
    `${header}import type { CommandDoc } from "./docs.js";\n\n` +
      `export const DOCS_VERSION = ${JSON.stringify(version)};\n\n` +
      `export const COMMAND_DOCS: Readonly<Record<string, CommandDoc>> = ${JSON.stringify(sorted(docs))};\n`,
  );
  await writeFile(
    FLAGS_FILE,
    `${header}\n/** Every command's and container subcommand's flags, keyed \`SET\` or \`CONFIG SET\`. */\n` +
      `export const COMMAND_FLAGS: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(sorted(flags))};\n`,
  );
}

await main();
