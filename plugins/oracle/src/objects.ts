import type {
  CheckDesign,
  ColumnDesign,
  DdlContext,
  DdlScript,
  ForeignKeyDesign,
  IndexDesign,
  ObjectChange,
  ObjectEditor,
  ObjectKind,
  TableDesign,
} from "@table-craft/plugin-api";
import {
  ddlScript,
  designError,
  NOTHING_TO_CHANGE,
  tableDesignOf,
  tableDifference,
  unchanged,
  validateDesign,
} from "@table-craft/plugin-api/sql";

const INDENT = "  ";
const IDENTITY = "GENERATED BY DEFAULT AS IDENTITY";

/**
 * Oracle commits before and after every DDL statement
 * (https://docs.oracle.com/en/database/oracle/oracle-database/23/cncpt/transactions.html).
 */
export const IMPLICIT_COMMIT_NOTE =
  "Oracle commits each DDL statement on its own: it cannot be rolled back, and a failure part-way keeps the statements before it.";

const CREATE_SCHEMA_REFUSED =
  "Oracle makes a schema with its user: run CREATE USER, which needs the CREATE USER privilege, then refresh the tree.";

const TYPES = [
  "NUMBER",
  "NUMBER(10)",
  "NUMBER(12, 2)",
  "VARCHAR2(255 CHAR)",
  "NVARCHAR2(255)",
  "CLOB",
  "BLOB",
  "RAW(16)",
  "DATE",
  "TIMESTAMP",
  "TIMESTAMP WITH TIME ZONE",
  "BINARY_DOUBLE",
  "BINARY_FLOAT",
  "BOOLEAN",
  "JSON",
];

const KEYWORDS: Readonly<Partial<Record<ObjectKind, string>>> = {
  table: "TABLE",
  view: "VIEW",
  materializedView: "MATERIALIZED VIEW",
  sequence: "SEQUENCE",
  function: "FUNCTION",
  procedure: "PROCEDURE",
};

/** Oracle's actions on delete; it has no `ON UPDATE` and spells the default by leaving it out. */
const DELETE_ACTIONS = new Set(["CASCADE", "SET NULL"]);
const DEFAULT_ACTIONS = new Set(["NO ACTION", "RESTRICT"]);

export interface OracleObjectOptions {
  /** Spells a column, index or constraint name, quoting only where needed. */
  readonly name: (identifier: string) => string;
  readonly text: (value: string) => string;
}

/** Object DDL for Oracle, whose DDL commits on its own, so nothing runs in one transaction. */
export function oracleObjects(options: OracleObjectOptions): ObjectEditor {
  const { name, text } = options;
  const script = (statements: readonly string[]): DdlScript =>
    ddlScript(statements, { transactional: false, notes: [IMPLICIT_COMMIT_NOTE] });

  function fallback(column: ColumnDesign): string {
    return (column.default ?? "").trim();
  }

  function columnDefinition(column: ColumnDesign): string {
    return [
      name(column.name),
      column.type.trim(),
      column.autoIncrement ? IDENTITY : fallback(column) === "" ? "" : `DEFAULT ${fallback(column)}`,
      column.nullable ? "" : "NOT NULL",
    ]
      .filter((part) => part !== "")
      .join(" ");
  }

  function columns(list: readonly string[]): string {
    return list.map(name).join(", ");
  }

  function foreignKey(key: ForeignKeyDesign, context: DdlContext): string {
    if (key.onUpdate !== null && !DEFAULT_ACTIONS.has(key.onUpdate.toUpperCase())) {
      throw designError(`Oracle has no ON UPDATE action; clear it on ${key.name}.`);
    }
    const onDelete = key.onDelete?.toUpperCase() ?? null;
    if (onDelete !== null && !DELETE_ACTIONS.has(onDelete) && !DEFAULT_ACTIONS.has(onDelete)) {
      throw designError(`Oracle deletes with CASCADE or SET NULL only; change ON DELETE on ${key.name}.`);
    }
    const target = context.qualifiedName(key.target.path, key.target.relation);
    const action = onDelete !== null && DELETE_ACTIONS.has(onDelete) ? ` ON DELETE ${onDelete}` : "";
    return `CONSTRAINT ${name(key.name)} FOREIGN KEY (${columns(key.columns)}) REFERENCES ${target} (${columns(key.target.columns)})${action}`;
  }

  function check(entry: CheckDesign): string {
    return `CONSTRAINT ${name(entry.name)} CHECK (${entry.expression.trim()})`;
  }

  function createIndex(index: IndexDesign, table: string, path: readonly string[], context: DdlContext): string {
    const indexName = context.qualifiedName(path, index.name);
    return `CREATE ${index.unique ? "UNIQUE " : ""}INDEX ${indexName} ON ${table} (${columns(index.columns)});`;
  }

  /** Oracle stores an empty comment as none, so clearing one writes ''. */
  function comment(target: string, value: string | null): string {
    return `COMMENT ON ${target} IS ${text(value ?? "")};`;
  }

  function createTable(path: readonly string[], design: TableDesign, context: DdlContext): DdlScript {
    validateDesign(design);
    const table = context.qualifiedName(path, design.name);
    const parts = [
      ...design.columns.map(columnDefinition),
      ...(design.primaryKey.length > 0 ? [`PRIMARY KEY (${columns(design.primaryKey)})`] : []),
      ...design.foreignKeys.map((key) => foreignKey(key, context)),
      ...design.checks.map(check),
    ];
    return script([
      `CREATE TABLE ${table} (\n${parts.map((part) => INDENT + part).join(",\n")}\n);`,
      ...design.indexes.map((index) => createIndex(index, table, path, context)),
      ...(design.comment === null || design.comment === "" ? [] : [comment(`TABLE ${table}`, design.comment)]),
      ...design.columns
        .filter((column) => column.comment !== null && column.comment !== "")
        .map((column) => comment(`COLUMN ${table}.${name(column.name)}`, column.comment)),
    ]);
  }

  function alterColumn(table: string, before: ColumnDesign, after: ColumnDesign): string[] {
    const modify = (clause: string): string => `ALTER TABLE ${table} MODIFY (${name(after.name)} ${clause});`;
    const statements: string[] = [];
    if (before.name !== after.name) {
      statements.push(`ALTER TABLE ${table} RENAME COLUMN ${name(before.name)} TO ${name(after.name)};`);
    }
    if (before.type.trim() !== after.type.trim()) statements.push(modify(after.type.trim()));
    if (before.nullable !== after.nullable) statements.push(modify(after.nullable ? "NULL" : "NOT NULL"));
    if (before.autoIncrement !== after.autoIncrement) {
      if (after.autoIncrement) {
        throw designError(
          `Oracle cannot make the existing column ${after.name} an identity; add a new column instead.`,
        );
      }
      statements.push(modify("DROP IDENTITY"));
    }
    if (!after.autoIncrement && fallback(before) !== fallback(after)) {
      statements.push(modify(`DEFAULT ${fallback(after) === "" ? "NULL" : fallback(after)}`));
    }
    if ((before.comment ?? "") !== (after.comment ?? "")) {
      statements.push(comment(`COLUMN ${table}.${name(after.name)}`, after.comment));
    }
    return statements;
  }

  function alterTable(path: readonly string[], design: TableDesign, context: DdlContext): DdlScript {
    validateDesign(design);
    const current = context.current;
    if (current === null) throw designError("The table is not described; synchronize the data source and try again.");
    const difference = tableDifference(current, design);
    if (unchanged(difference)) return ddlScript([], { transactional: false, notes: [NOTHING_TO_CHANGE] });
    const table = context.qualifiedName(path, current.name);
    const alter = (clause: string): string => `ALTER TABLE ${table} ${clause};`;
    return script([
      ...difference.droppedForeignKeys.map((key) => alter(`DROP CONSTRAINT ${name(key.name)}`)),
      ...difference.droppedChecks.map((entry) => alter(`DROP CONSTRAINT ${name(entry.name)}`)),
      ...difference.droppedIndexes.map((index) => `DROP INDEX ${context.qualifiedName(path, index.name)};`),
      ...(difference.primaryKeyChanged && current.primaryKeyName !== null
        ? [alter(`DROP CONSTRAINT ${name(current.primaryKeyName)}`)]
        : []),
      ...difference.droppedColumns.map((column) => alter(`DROP COLUMN ${name(column.name)}`)),
      ...difference.changedColumns.flatMap(({ before, after }) => alterColumn(table, before, after)),
      ...difference.addedColumns.flatMap((column) => [
        alter(`ADD (${columnDefinition(column)})`),
        ...(column.comment === null || column.comment === ""
          ? []
          : [comment(`COLUMN ${table}.${name(column.name)}`, column.comment)]),
      ]),
      ...(difference.primaryKeyChanged && design.primaryKey.length > 0
        ? [alter(`ADD PRIMARY KEY (${columns(design.primaryKey)})`)]
        : []),
      ...difference.addedChecks.map((entry) => alter(`ADD ${check(entry)}`)),
      ...difference.addedForeignKeys.map((key) => alter(`ADD ${foreignKey(key, context)}`)),
      ...difference.addedIndexes.map((index) => createIndex(index, table, path, context)),
      ...(difference.commentChanged ? [comment(`TABLE ${table}`, design.comment)] : []),
      ...(difference.renamedTo === null ? [] : [alter(`RENAME TO ${name(difference.renamedTo)}`)]),
    ]);
  }

  function keyword(kind: ObjectKind, objectName: string): string {
    const word = KEYWORDS[kind];
    if (word === undefined) throw designError(`Oracle cannot change a ${kind} here.`);
    if ((kind === "function" || kind === "procedure") && objectName.includes(".")) {
      throw designError(`${objectName} belongs to a package; change the package instead.`);
    }
    return word;
  }

  function change(edit: ObjectChange, context: DdlContext): DdlScript {
    switch (edit.kind) {
      case "createTable":
        return createTable(edit.path, edit.design, context);
      case "alterTable":
        return alterTable(edit.path, edit.design, context);
      case "rename": {
        if (edit.name.trim() === "") throw designError("Type the new name.");
        const target = context.qualifiedName(edit.path, edit.object.name);
        return script([`ALTER ${keyword(edit.object.kind, edit.object.name)} ${target} RENAME TO ${name(edit.name)};`]);
      }
      case "drop": {
        const kind = keyword(edit.object.kind, edit.object.name);
        const target = context.qualifiedName(edit.path, edit.object.name);
        const cascade = edit.cascade && (kind === "TABLE" || kind === "VIEW") ? " CASCADE CONSTRAINTS" : "";
        return script([`DROP ${kind} ${target}${cascade};`]);
      }
      case "truncate":
        return script([
          `TRUNCATE TABLE ${context.qualifiedName(edit.path, edit.relation)}${edit.cascade ? " CASCADE" : ""};`,
        ]);
      case "createNamespace":
        throw designError(CREATE_SCHEMA_REFUSED);
    }
  }

  return {
    features: {
      types: TYPES,
      checks: true,
      comments: true,
      cascade: true,
      truncate: true,
      namespaceKind: null,
      renamable: ["table"],
      droppable: ["table", "view", "materializedView", "sequence", "function", "procedure"],
    },
    design: (relation) => tableDesignOf(relation),
    script: change,
  };
}
