-- The demo shop the README GIFs are recorded against (plan 016). Deterministic: every row comes
-- from generate_series over fixed lists, so a re-recording shows the same data.

CREATE TABLE customers (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  email text NOT NULL UNIQUE,
  city text NOT NULL,
  joined_on date NOT NULL
);
COMMENT ON TABLE customers IS 'People who have placed at least one order';

CREATE TABLE products (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  category text NOT NULL,
  price numeric(10, 2) NOT NULL CHECK (price > 0),
  stock integer NOT NULL DEFAULT 0
);

CREATE TABLE orders (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id integer NOT NULL REFERENCES customers (id),
  status text NOT NULL DEFAULT 'pending',
  placed_at timestamp NOT NULL
);
CREATE INDEX orders_placed_at_idx ON orders (placed_at);

CREATE TABLE order_items (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id integer NOT NULL REFERENCES orders (id),
  product_id integer NOT NULL REFERENCES products (id),
  quantity integer NOT NULL CHECK (quantity > 0),
  unit_price numeric(10, 2) NOT NULL
);

