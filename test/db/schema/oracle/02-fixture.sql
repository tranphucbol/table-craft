-- Routines, so Execute Routine meets a default, an overload, a ref cursor, OUT and IN OUT
-- parameters and package members.
CREATE FUNCTION calc_fee(amount NUMBER, rate NUMBER DEFAULT 0.015) RETURN NUMBER IS
BEGIN
  RETURN ROUND(amount * rate, 2);
END;
/

CREATE PACKAGE billing AS
  FUNCTION calc_fee(amount NUMBER, rate NUMBER DEFAULT 0.015) RETURN NUMBER;
  FUNCTION calc_fee(amount NUMBER, currency VARCHAR2, rate NUMBER DEFAULT 0.015) RETURN NUMBER;
END billing;
/

CREATE PACKAGE BODY billing AS
  FUNCTION calc_fee(amount NUMBER, rate NUMBER DEFAULT 0.015) RETURN NUMBER IS
  BEGIN
    RETURN ROUND(amount * rate, 2);
  END;

  FUNCTION calc_fee(amount NUMBER, currency VARCHAR2, rate NUMBER DEFAULT 0.015) RETURN NUMBER IS
  BEGIN
    RETURN ROUND(amount * rate, 2) + CASE WHEN currency = 'USD' THEN 0 ELSE 1 END;
  END;
END billing;
/

CREATE FUNCTION customer_orders(customer NUMBER) RETURN SYS_REFCURSOR IS
  found SYS_REFCURSOR;
BEGIN
  OPEN found FOR SELECT o.id, o.total FROM orders o WHERE o.customer_id = customer ORDER BY o.id;
  RETURN found;
END;
/

CREATE PROCEDURE settle_order(order_id IN NUMBER, total OUT NUMBER, note IN OUT VARCHAR2) IS
BEGIN
  SELECT o.total INTO total FROM orders o WHERE o.id = order_id;
  note := note || ' settled';
END;
/

